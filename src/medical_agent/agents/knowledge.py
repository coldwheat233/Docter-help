KB_TOPICS_SUMMARY = "\n".join(
    f"- {kb['topic']}（关键词：{', '.join(kb['keywords'][:5])}）"
    + (f" → {kb['department']}" if kb.get('department') else "")
    for kb in KNOWLEDGE_BASE
)


KNOWLEDGE_PROMPT = """你是医疗预约系统的知识问答助手。

你不是医生，不能下医学诊断。但你可以：
1. 回答常见健康问题（饮食、护理、急救）
2. 指引患者去正确的科室
3. 判断是否需要急诊

你的知识库覆盖以下主题（{count} 条）：
{topics}

**重要规则**：
1. 每条知识都含"立即急诊"/"立即就医"等关键词，**必须告诉用户是否需要急诊**
2. 不确定时建议就医（不要"百度"自己当医生）
3. 不要编造医学知识
4. 简洁明了，3-5 句话
5. 如果患者想挂号，引导回主流程（"我可以帮您预约 X 科"）

**免责声明**（每次回答都要加）：本回答仅供参考，不能替代医生诊断。如有疑问请就医。
""".format(count=len(KNOWLEDGE_BASE), topics=KB_TOPICS_SUMMARY)


def build_knowledge_agent() -> "CompiledStateGraph":  # noqa: F821
    """构造知识问答 Agent。"""
    return create_react_agent(
        model=get_llm(),
        tools=[],  # 未来加 search_knowledge
        name=KNOWLEDGE_AGENT_NAME,
        prompt=KNOWLEDGE_PROMPT,
    )


def search_knowledge(query: str) -> list[dict]:
    """简单关键词匹配（替代向量检索的 stub）。

    第 2 周会改为 SQLite FTS5 + 向量检索。
    """
    query_lower = query.lower()
    results = []
    for kb in KNOWLEDGE_BASE:
        score = 0
        # 关键词命中
        for kw in kb["keywords"]:
            if kw.lower() in query_lower:
                score += 1
        # topic 命中
        if kb["topic"].lower() in query_lower:
            score += 2
        # 部门命中
        if kb.get("department") and kb["department"].lower() in query_lower:
            score += 1
        if score > 0:
            results.append({**kb, "score": score})
    results.sort(key=lambda x: x["score"], reverse=True)
    return results
